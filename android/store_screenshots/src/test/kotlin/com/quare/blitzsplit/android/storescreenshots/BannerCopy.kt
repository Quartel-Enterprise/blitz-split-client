/** A banner's title and description in one language. Keep both short: the frame wraps the description to 2 lines. */
internal data class BannerCopy(
    val title: String,
    val description: String,
)

internal fun bannerCopyOf(
    screen: StoreScreen,
    language: String,
): BannerCopy {
    val copies = bannerCopies.getValue(screen)
    return copies[language] ?: copies.getValue("en")
}

