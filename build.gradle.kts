// version.properties is the single source of truth for the app version: Gradle exposes it as the
// versionName/versionCode project properties and iosApp/project.yml reads the same file.
val appVersion: Map<String, String> = providers
    .fileContents(layout.projectDirectory.file("version.properties"))
    .asText
    .get()
    .lineSequence()
    .filter { line -> '=' in line && !line.trimStart().startsWith("#") }
    .associate { line ->
        val (key, value) = line.split('=', limit = 2)
        key.trim() to value.trim()
    }

allprojects {
    appVersion.forEach { (key, value) -> extra[key] = value }
}

moduleGraphAssert {
    // Production source sets only: test-only edges are not part of the architecture.
    configurations = setOf(
        "api",
        "implementation",
        "commonMainApi",
        "commonMainImplementation",
        "androidMainImplementation",
        "appleMainImplementation",
        "jsMainImplementation",
        "jvmMainImplementation",
    )
    // :shared is the composition root of the shared code: it wires every feature, so nothing
    // depends on it except the apps. Features never see each other: what two of them share lives
    // in core. The Android UI of a feature sees only its own presentation module.
    restricted = arrayOf(
        ":feature:.* -X> :feature:.*",
        ":core:.* -X> :(feature|android|shared).*",
        ":feature:.* -X> :(android|shared).*",
        ":android:feature:.* -X> :android:feature:.*",
        ":android:(designsystem|feature:.*) -X> :shared",
        // The :testing modules hold fakes for tests, so production code never depends on them.
        ":(?!\\S*:testing ).* -X> :.*:testing",
    )
}

// The root merges every module that applies Kover (configureCoverage in build-logic) into one
// report and sets the bar.
private val coverageVariant = "ci"
private val coverageMinPercent = 80

kover {
    currentProject {
        createVariant(coverageVariant) {}
    }
    reports {
        filters {
            excludes {
                // Koin modules are wiring, with no behaviour of their own
                packages("*.di")
                // Generated by Room, kotlinx.serialization and BuildKonfig
                classes("*_Impl", "*_Impl$*", "*$\$serializer", "*\$DefaultImpls")
                packages("*.generated")
                // Platform bridges for Swift and JS: exercised by the apps, not by unit tests
                packages("*.bridge")
            }
        }
        verify {
            rule("Line coverage of the merged report") {
                minBound(coverageMinPercent)
            }
        }
    }
}

dependencies {
    subprojects
        .filter { it.path.startsWith(":core:") || it.path.startsWith(":feature:") }
        .filterNot { it.path.endsWith(":testing") || it.path.startsWith(":core:provider") }
        .forEach { kover(it) }
}
